#!/usr/bin/env python3
"""Generate fleet/docker-compose.yml: 50 containers (20 web, 20 app, 10 db).

A few hosts are given deliberate faults so the audit has something real to find.
Edit INCIDENTS to change the scenario, then run `make fleet-up` again.
"""
from pathlib import Path

FLEET = {"web": 20, "app": 20, "db": 10}
BASE_SSH_PORT = 2201
DATA_VOLUME_MB = 50

# host -> environment variables that break it on purpose
INCIDENTS = {
    "web-07": {"FILL_MB": "46"},       # /data at ~92%  -> CRITICAL disk
    "app-03": {"FILL_MB": "42"},       # /data at ~84%  -> WARNING disk
    "web-12": {"SKIP_SERVICE": "1"},   # nginx not running -> CRITICAL
    "app-11": {"SKIP_SERVICE": "1"},   # app server not running -> CRITICAL
    "db-02": {"BROKEN_SSH": "1"},      # sshd not running -> UNREACHABLE
}


def hosts():
    """Yield (name, role, ssh_port) for every host, in a stable order."""
    port = BASE_SSH_PORT
    for role, count in FLEET.items():
        for number in range(1, count + 1):
            yield f"{role}-{number:02d}", role, port
            port += 1


def render_service(name, role, port):
    env = {"ROLE": role, **INCIDENTS.get(name, {})}
    env_lines = "\n".join(f'      {key}: "{value}"' for key, value in env.items())
    return f"""  {name}:
    <<: *node
    hostname: {name}
    labels:
      fleet.audit: "true"
      fleet.role: "{role}"
    ports:
      - "127.0.0.1:{port}:22"
    environment:
{env_lines}
"""


def main():
    header = f"""# GENERATED by scripts/generate_fleet.py. Do not edit by hand.
name: fleet-audit

x-node: &node
  image: fleet-node:latest
  pull_policy: never
  init: true
  restart: "no"
  tmpfs:
    - /data:size={DATA_VOLUME_MB}m,mode=1777

services:
"""
    body = "\n".join(render_service(*host) for host in hosts())
    out = Path(__file__).resolve().parent.parent / "fleet" / "docker-compose.yml"
    out.write_text(header + body)
    total = sum(FLEET.values())
    print(f"Wrote {out} ({total} hosts, {len(INCIDENTS)} with seeded incidents)")


if __name__ == "__main__":
    main()
